#!/usr/bin/env python3
"""Embeds p5.js's GLSL shaders (src/webgl/shaders) into webgl/shader_sources.mbt.

Usage: python3 tools/gen_shaders.py [path/to/p5.js]
The sources are copied verbatim (LGPL-2.1, like p5.js itself).
"""
import os, re, sys

root = sys.argv[1] if len(sys.argv) > 1 else '.repos/p5.js'
src = os.path.join(root, 'src/webgl/shaders')
files = []
for d, _, names in os.walk(src):
    for n in sorted(names):
        if re.search(r'\.(vert|frag|glsl)$', n):
            files.append(os.path.join(d, n))
files.sort()

def ident(path):
    rel = os.path.relpath(path, src)
    return 'glsl_' + re.sub(r'[^A-Za-z0-9]+', '_', rel).lower()

out = ['// Generated by tools/gen_shaders.py from p5.js src/webgl/shaders.',
       '// DO NOT EDIT: re-run the script instead.', '']
for f in files:
    text = open(f).read()
    out.append('///|')
    out.append(f'/// {os.path.relpath(f, src)}')
    out.append(f'let {ident(f)} : String =')
    for line in text.split('\n'):
        out.append('  #|' + line)
    out.append('')
open('webgl/shader_sources.mbt', 'w').write('\n'.join(out))
print(f'{len(files)} shaders')
